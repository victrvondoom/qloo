// Writes reports/human-evaluation-summary.md from the responses actually in the database.
// With zero responses it says so. It never fills in or estimates anything.
//
//   npm run study:report

import { mkdirSync, writeFileSync } from "node:fs";
import { allResponses } from "../src/lib/study-store";
import { CRITERIA, MIN_INTERPRETABLE, QUESTIONS, SYSTEM_NAMES, summarize, type StudySystem } from "../src/lib/study";

const pct = (x: number | null) => (x === null ? "–" : `${Math.round(x * 100)}%`);

async function main() {
  const rows = await allResponses();
  const s = summarize(rows);
  const out: string[] = ["# Human evaluation summary", ""];
  if (s.responses === 0) {
    out.push("**NO HUMAN DATA COLLECTED.** Zero responses have been recorded. Nothing below is simulated or estimated, and no claim about human preference can be made from this report.", "");
    out.push("The study workflow is implemented (`/study`, `docs/HUMAN_EVALUATION.md`). This file is regenerated by `npm run study:report` from the responses in the database.");
  } else {
    out.push(`Generated ${new Date().toISOString()} from ${s.responses} anonymous response(s). Data modes: ${s.dataModes.join(", ")}.`, "");
    out.push(s.interpretable ? "" : `**Fewer than ${MIN_INTERPRETABLE} responses: too few to read as a preference. Treat as anecdote.**`, "");
    for (const p of s.byPair) {
      const [x, y] = p.pair.split(" vs ") as [StudySystem, StudySystem];
      out.push(`## ${SYSTEM_NAMES[x]} vs ${SYSTEM_NAMES[y]} (${p.responses} responses, mean confidence ${p.meanConfidence}/5)`, "");
      out.push(`| Question | ${SYSTEM_NAMES[x]} | ${SYSTEM_NAMES[y]} | Equal | Neither | ${SYSTEM_NAMES[x]} share of decisive (95% CI) |`, "|---|---|---|---|---|---|");
      for (const c of CRITERIA) {
        const k = p.criteria[c];
        const w = k.firstShareOfDecisive;
        out.push(`| ${QUESTIONS[c]} | ${k.first} | ${k.second} | ${k.equal} | ${k.neither} | ${w.p === null ? "–" : `${pct(w.p)} [${pct(w.lo)}, ${pct(w.hi)}] (n=${w.n})`} |`);
      }
      out.push("");
    }
    out.push("## Cases and versions", "", ...s.byCase.map((c) => `- ${c.caseId}: ${c.responses} response(s), version(s) ${c.versions.join(", ")}`), "");
  }
  out.push("", "## Limitations", "", "- Participants judge fictional clients, not their own taste.", "- Samples are small and self-selected.", "- Specification wording can sway a choice independently of quality.", "- Cases built from synthetic demo data say so; they are not evidence about Qloo's real data.");
  mkdirSync("reports", { recursive: true });
  writeFileSync("reports/human-evaluation-summary.md", out.join("\n") + "\n");
  console.log(`wrote reports/human-evaluation-summary.md (${s.responses} responses)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
